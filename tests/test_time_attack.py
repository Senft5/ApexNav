@pytest.fixture(scope="module")
def out():
    return json.loads(subprocess.run([NODE, "-e", RUNNER, ROOT], capture_output=True, text=True, check=True).stdout)


def test_clock_and_gap(out):
    assert out["clock"] == ["1:15", "1:02:05", "0:10", "--", "--"]
    assert out["gap"] == ["", "+0:03", ""]


def test_days_left_counts_today(out):
    assert out["days"] == [3, 1, None]


def test_the_phone_sends_the_area_not_where_it_is(out):
    # the middle of the quarter-degree area (the owner, TestFlight 2026-11-12: a 1-degree area put the loop an hour away)
    assert out["area"] == [{"lat": 39.375, "lon": -84.625}, {"lat": -33.875, "lon": 151.125}, None]


def test_runs_are_the_quickest_timed_pass_this_week_on_a_backed_up_circuit(out):
    # the quickest each day from the first day asked (the server keeps your quickest each day), newest first
    assert out["runs"] == [{"segment_id": "mine1", "time_s": 195, "driver_score": 700, "driven_on": "2026-11-12"},
                           {"segment_id": "mine1", "time_s": 201, "driver_score": 800, "driven_on": "2026-11-10"}]
    assert out["runsSince"] == [{"segment_id": "mine1", "time_s": 195, "driver_score": 700, "driven_on": "2026-11-12"}]   # nothing before you entered
    assert out["runsMany"] == {"n": 20, "first": "2026-10-30", "last": "2026-10-11"}   # one request: the 20 latest days
    assert out["none"] == []


def test_entered_stage_copy(out):
    assert out["copy"] == {"id": "new1", "name": "Dry Ridge", "length_m": 2500, "geom": "[[39.2,-84.6],[39.21,-84.61],[39.3,-84.5]]",
                           "lat0": 39.2, "lon0": -84.6, "lat1": 39.3, "lon1": -84.5, "origin": "C1", "synced": True}
    assert out["nocopy"] is None


def test_the_seed_draws_the_same_start_and_length_on_every_phone(out):
    assert out["rng"][0] == out["rng"][1] and out["rng"][0] != out["rng"][2] and 0 <= out["rng"][0] < 1
    hubs = out["hubs"]
    # six starts in the middle half of the area's own tile, drawn from the seed
    assert len(hubs) == 6 and all(x["key"].startswith("380_516#") for x in hubs)
    assert all(39.0625 <= x["lat"] <= 39.1875 and -84.9375 <= x["lon"] <= -84.8125 for x in hubs)
    assert len({(x["lat"], x["lon"]) for x in hubs}) == 6
    assert out["hubsAgain"] == hubs                          # the order the tiles come in doesn't change the draw
    assert out["hubsOther"] != hubs                          # next week, other starts
    assert out["hubsNone"] == [] and out["hubsNoTile"] == []   # no road tile for the area here: nothing
    assert all(8 <= km <= 16 for km in out["km"])


def test_one_of_the_best_three_loops_is_picked_at_random(out):
    assert out["picks"] == [9000, 11000, 12000]             # never the 30 km one, the subdivision one, the unmeasured one or the fourth
    assert out["pickSame"] is True and out["pickNone"] is None
    assert out["names"] == ["Dry Ridge Road loop", "Local loop", "Local loop", "Ridge Rd loop"]


def test_a_fixed_loop_is_the_routers_best_away_from_the_areas_others(out):
    """The owner, 2026-11-12: "static best roads". A season's loop is the router's top loop that fits (not one of three at
    random), started away from the area's other loops, and posted for its slot."""
    assert out["best"] == [11000, 11000]
    assert out["skipped"] is True and out["slot2"] == [1] and out["made2"] is True


def test_the_featured_loop_is_this_weeks_time_attack(out):
    w, month_entrants, none, old = out["week"]
    assert w == {"week": "2026-11-09", "ends_on": "2026-11-15", "today": "2026-11-12", "cell": "39,-85",
                 "circuit": {"segment_id": "B", "name": "B loop", "length_m": 11000, "geom": "[[1,2]]"}, "entered": True, "entrants": 4, "you": {"place": 2}}
    assert month_entrants == 0                               # a month's board isn't this week's
    assert none is None and old is None


def test_the_foot_says_when_the_loops_change(out):
    assert out["foot"] == ["Featured changes Mondays. New loops in January. Drive within the law.",
                           "Featured changes Mondays. New loops in April. Drive within the law.",
                           "Featured changes Mondays. Drive within the law."]


def test_a_loop_through_a_neighbourhood_is_refused(out):
    """The owner's TestFlight note (2026-11-12): "goes only through a neighborhood". More than 500 m or 5 % of
    neighbourhood street (graph_router.js loopRoute streetM, streetShare), or not measured at all, and it isn't the loop."""
    assert out["streety"] == [False, True, True, True]


def test_the_loop_line_is_thinned_and_closed_on_its_start(out):
    g = out["geom"]
    assert 400 <= g["n"] <= 600                              # 10 km at a point every 20 m or more
    assert g["first"] == g["last"]
    assert g["open"] is True                                 # an open line is closed on its start


def test_make_loop_tries_the_next_start_and_posts_the_first_loop_found(out):
    assert len(out["asked"]) == 2                            # the first start had nothing, the second did
    assert out["posted"] == [{"cell": "39,-85", "seed": "2026-11-09|39,-85|0", "name": out["posted"][0]["name"], "n": out["posted"][0]["n"]}]
    assert out["posted"][0]["n"] >= 10
    assert out["made"] == {"circuit": {"name": out["posted"][0]["name"]}, "kept": True}
    assert out["noneMade"] is None                           # an area with no road tiles: nothing built


def test_the_log_sends_runs():
    """The Log (analysis.html) loads time_attack.js and sends the week's runs after the stages sync: without it the board
    never had a time on it (round two sweep, 2026-11-11)."""
    with open(os.path.join(ROOT, "web", "analysis.html"), encoding="utf-8") as f:
        page = f.read()
    assert '<script src="time_attack.js"></script>' in page
    sync = page[page.index("async function syncSegments()"):]
    sync = sync[:sync.index("const act = segs.find(")]
    assert "await ApexTimeAttack.sendRuns(ApexSync, segs, passesFor)" in sync
    assert "ApexTimeAttack.placeLine" in sync   # and says your place after it


