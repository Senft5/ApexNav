"""Export a Sensor Logger drive into a compact JS data file for the web cockpit.

Usage:
    python tools/export_web_profile.py <drive.zip|dir> --name "Pebble Ridge Ln" --out web/data/pebble_ridge.js

The output file registers itself on ``window.APEX_DRIVES`` so it can be loaded via a
plain ``<script>`` tag (works from file:// and inside an iOS WKWebView). To add another
drive, export a new file into ``web/data/`` and list it in ``web/data/manifest.js``.
"""
from __future__ import annotations

import argparse
import datetime as dt
import io
import json
import os
import re
import sys
import zipfile

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from core.kinematics import ingest_sensor_logger_drive  # noqa: E402

# (field, decimals) — order defines the column layout of every row.
FIELDS = [
    ("distance_m", 1),
    ("lat", 6),
    ("lon", 6),
    ("elevation_m", 1),
    ("grade_pct", 1),
    ("speed_mph", 1),
    ("lon_g", 3),
    ("lat_g", 3),
    ("camber_deg", 1),
    ("crest_vertical_g", 3),
    ("roughness_rms", 4),
    ("engagement_score", 2),
]

SEGMENT_M = 5.0
GRADE_WINDOW_M = 50.0


def slugify(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_") or "drive"


def read_metadata(source: str) -> dict:
    """Best-effort read of Sensor Logger Metadata.csv (device + recording epoch)."""
    try:
        if zipfile.is_zipfile(source):
            with zipfile.ZipFile(source) as zf:
                raw = zf.read("Metadata.csv").decode("utf-8", "replace")
        else:
            with open(os.path.join(source, "Metadata.csv"), encoding="utf-8") as f:
                raw = f.read()
        row = pd.read_csv(io.StringIO(raw)).iloc[0].to_dict()
    except Exception:
        return {}
    meta = {"device": str(row.get("device name", "") or "")}
    epoch_ms = row.get("recording epoch time")
    tz = row.get("recording timezone")
    try:
        stamp = pd.Timestamp(int(epoch_ms), unit="ms", tz="UTC")
        if isinstance(tz, str) and tz:
            stamp = stamp.tz_convert(tz)
        meta["date"] = stamp.isoformat()
    except Exception:
        pass
    return meta


def smooth_display_series(segments: pd.DataFrame) -> pd.DataFrame:
    """Return a copy with display-friendly elevation/grade.

    Barometric altitude at 5 m spacing is noisy enough that a raw finite-difference grade
    jumps by several percent between neighbouring segments. For display we derive grade
    from a ~50 m centred rolling-mean elevation and then lightly smooth the result.
    """
    out = segments.sort_values("distance_m").reset_index(drop=True).copy()
    win = max(3, int(round(GRADE_WINDOW_M / SEGMENT_M)) | 1)  # odd window
    elev_s = out["elevation_m"].rolling(win, center=True, min_periods=1).mean()
    dist = out["distance_m"].to_numpy(dtype=float)
    if len(out) > 2:
        d_elev = np.gradient(elev_s.to_numpy(), dist)
        grade = pd.Series(np.clip(d_elev * 100.0, -35.0, 35.0))
        out["grade_pct"] = grade.rolling(win, center=True, min_periods=1).mean().to_numpy()
    else:
        out["grade_pct"] = 0.0
    out["elevation_m"] = elev_s.to_numpy()
    return out


def build_payload(source: str, name: str, drive_id: str) -> dict:
    _raw, _R, segments = ingest_sensor_logger_drive(source)
    segments = smooth_display_series(segments)
    segments = segments.replace([np.inf, -np.inf], np.nan).dropna(subset=["lat", "lon"])
    segments = segments.fillna(0.0)

    cols = []
    for field, decimals in FIELDS:
        vals = np.round(segments[field].to_numpy(dtype=float), decimals)
        cols.append([int(v) if decimals == 0 or float(v).is_integer() else float(v) for v in vals])
    rows = [list(r) for r in zip(*cols)]

    meta = read_metadata(source)
    return {
        "id": drive_id,
        "name": name,
        "date": meta.get("date", ""),
        "device": meta.get("device", ""),
        "segment_m": SEGMENT_M,
        "fields": [f for f, _ in FIELDS],
        "rows": rows,
    }


def write_js(payload: dict, out_path: str) -> None:
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    rows = payload.pop("rows")
    head = json.dumps(payload, separators=(",", ":"))[:-1]
    body = ",\n".join(json.dumps(r, separators=(",", ":")) for r in rows)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/export_web_profile.py — do not edit by hand.\n")
        f.write("window.APEX_DRIVES = window.APEX_DRIVES || [];\n")
        f.write("window.APEX_DRIVES.push(" + head + ',"rows":[\n' + body + "\n]});\n")
    payload["rows"] = rows


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source", help="Sensor Logger export (.zip or extracted directory)")
    ap.add_argument("--name", required=True, help='Display name, e.g. "Pebble Ridge Ln"')
    ap.add_argument("--id", help="Stable drive id (defaults to slug of --name)")
    ap.add_argument("--out", help="Output .js path (defaults to web/data/<slug>.js)")
    args = ap.parse_args(argv)

    drive_id = args.id or slugify(args.name)
    out = args.out or os.path.join(ROOT, "web", "data", f"{drive_id}.js")
    payload = build_payload(args.source, args.name, drive_id)
    write_js(payload, out)
    rows = payload["rows"]
    km = rows[-1][0] / 1000.0 if rows else 0.0
    print(f"Wrote {out}: {len(rows)} segments, {km:.2f} km, {os.path.getsize(out) / 1024:.0f} KiB")
    print(f'Remember to list it in web/data/manifest.js: "{os.path.basename(out)}"')
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
