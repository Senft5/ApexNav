#!/usr/bin/env python3
"""Render the route engine's flowchart (the Mermaid blocks and weights tables in docs/ROUTE_ENGINE.md, section Flowchart)
into a self-contained page for a phone: docs/design/route_engine_flow.html (Mermaid from a pinned CDN version, light and
dark). tests/test_route_engine_doc.py fails if the page is out of date. Run: python3 tools/route_engine_flow.py"""
import html
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "ROUTE_ENGINE.md"
OUT = ROOT / "docs" / "design" / "route_engine_flow.html"
MERMAID = "https://cdn.jsdelivr.net/npm/mermaid@10.9.1/dist/mermaid.min.js"


def section(md):
    start = md.index("## Flowchart")
    end = md.index("\n## ", md.index("## Weights (checked against the code)") + 5)
    return md[start:end]


def table_html(lines):
    rows = [[c.strip() for c in l.strip().strip("|").split("|")] for l in lines if not re.match(r"^\|[-| ]+\|$", l.strip())]
    head, body = rows[0], rows[1:]
    th = "".join(f"<th>{html.escape(c)}</th>" for c in head)
    tb = "".join("<tr>" + "".join(f"<td>{html.escape(c)}</td>" for c in r) + "</tr>" for r in body)
    return f'<div class="scroll"><table><thead><tr>{th}</tr></thead><tbody>{tb}</tbody></table></div>'


def inline(t):
    t = html.escape(t)
    return re.sub(r"`([^`]+)`", r"<code>\1</code>", t)


def render(md):
    sec = section(md)
    out, para, tbl, i = [], [], [], 0
    lines = sec.split("\n")
    flush = lambda: (out.append(f"<p>{inline(' '.join(para))}</p>") if para else None, para.clear())
    while i < len(lines):
        l = lines[i]
        if l.startswith("```mermaid"):
            flush(); j = i + 1; src = []
            while not lines[j].startswith("```"):
                src.append(lines[j]); j += 1
            out.append(f'<div class="scroll"><pre class="mermaid">{html.escape(chr(10).join(src))}</pre></div>'); i = j + 1; continue
        if l.startswith("|"):
            flush(); tbl.append(l); i += 1
            if i >= len(lines) or not lines[i].startswith("|"):
                out.append(table_html(tbl)); tbl.clear()
            continue
        if l.startswith("### "):
            flush(); out.append(f"<h2>{inline(l[4:])}</h2>")
        elif l.startswith("## "):
            flush(); out.append(f"<h1>{inline(l[3:])}</h1>")
        elif not l.strip():
            flush()
        else:
            para.append(l.strip())
        i += 1
    flush()
    body = "\n".join(out)
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Route engine flow</title>
<!-- Generated by tools/route_engine_flow.py from docs/ROUTE_ENGINE.md; do not edit by hand. -->
<style>
:root {{ --bg: #faf8f4; --fg: #1d1b18; --muted: #6a645b; --line: #d9d3c8; --code: #efeae1; }}
@media (prefers-color-scheme: dark) {{ :root {{ --bg: #141311; --fg: #ece7de; --muted: #a59e92; --line: #39352f; --code: #24211d; }} }}
html, body {{ background: var(--bg); color: var(--fg); margin: 0; }}
body {{ font: 15px/1.5 -apple-system, system-ui, "Segoe UI", sans-serif; padding: 16px; max-width: 1100px; margin: 0 auto; box-sizing: border-box; }}
h1 {{ font-size: 1.4rem; margin: 0.5rem 0 1rem; }} h2 {{ font-size: 1.1rem; margin: 1.8rem 0 0.6rem; }}
p {{ color: var(--muted); }} code {{ background: var(--code); padding: 0 4px; border-radius: 4px; font-size: 0.92em; }}
.scroll {{ overflow-x: auto; -webkit-overflow-scrolling: touch; border: 1px solid var(--line); border-radius: 8px; margin: 0.5rem 0 1rem; }}
pre.mermaid {{ margin: 0; padding: 12px; min-width: 640px; background: transparent; }}
table {{ border-collapse: collapse; width: 100%; font-size: 0.9rem; }}
th, td {{ border-bottom: 1px solid var(--line); padding: 6px 10px; text-align: left; vertical-align: top; }}
th {{ position: sticky; top: 0; background: var(--bg); }}
</style>
</head>
<body>
{body}
<script src="{MERMAID}"></script>
<script>
  const dark = window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches;
  mermaid.initialize({{ startOnLoad: true, theme: dark ? 'dark' : 'neutral', securityLevel: 'strict', flowchart: {{ htmlLabels: true, wrappingWidth: 260, useMaxWidth: false }} }});
</script>
</body>
</html>
"""


def main():
    page = render(DOC.read_text())
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == page else 1)
    OUT.write_text(page)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
