"""Generate ApexKit/Tests/Fixtures/live_fixture.json from core/live_pipeline.py.

A deterministic synthetic drive: crooked phone mount, calibration tap, straight pull,
4-degree banked left turn, rough pavement, a crest, 1 Hz GPS + barometer. The Swift
tests replay the exact inputs and must reproduce every recorded output.

  python tools/make_live_fixture.py          # rewrite the fixture
  python tools/make_live_fixture.py --check  # exit 1 if the fixture is stale (CI)
"""
from __future__ import annotations

import argparse
import json
import math
import os
import sys

import numpy as np
from scipy.spatial.transform import Rotation

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from core import live_pipeline as lp  # noqa: E402

OUT = os.path.join(ROOT, "ApexKit", "Tests", "Fixtures", "live_fixture.json")
FS = 100.0
DURATION_S = 30.0
MOUNT_EULER_DEG = [-70.0, 10.0, 95.0]
BANK_RAD = math.radians(4.0)
LAT0, LON0 = 39.2400, -84.7000


def build() -> dict:
    R = Rotation.from_euler("xyz", MOUNT_EULER_DEG, degrees=True).as_matrix()   # vehicle -> phone
    rng = np.random.default_rng(42)
    n = int(DURATION_S * FS)
    t = np.arange(n) / FS

    speed = np.zeros(n)
    ax = np.zeros(n)
    yaw = np.zeros(n)
    for i, ti in enumerate(t):
        if 2.0 <= ti < 5.0:
            ax[i] = 3.0
            speed[i] = 3.0 * (ti - 2.0)
        elif ti >= 5.0:
            speed[i] = 9.0 + min(11.0, 2.0 * (ti - 5.0))
            ax[i] = 2.0 if ti < 10.5 else 0.0
        if 12.0 <= ti < 22.0:
            yaw[i] = 0.25
    ay = speed * yaw * math.cos(BANK_RAD) - lp.G * math.sin(BANK_RAD) * (yaw != 0)
    az = 0.8 * np.sin(2 * math.pi * 12.0 * t) * (t > 5) + rng.normal(0, 0.15, n) * (t > 2)
    az += np.where((t > 25) & (t < 26.5), -1.5 * np.sin(math.pi * (t - 25) / 1.5), 0.0)   # crest unweighting

    accel_phone = np.column_stack([ax, ay, az]) @ R.T
    gyro_phone = np.column_stack([np.zeros(n), np.zeros(n), yaw]) @ R.T + rng.normal(0, 0.002, (n, 3)) * (t > 2)[:, None]
    gravity_g = (R @ np.array([0.0, 0.0, -1.0]))                       # CoreMotion gravity (points down), in g

    pipe = lp.IMUPipeline()
    outputs, mounts = [], []
    calibrated_at = int(1.0 * FS)
    for i in range(n):
        if i == calibrated_at:
            pipe.mount.lock_vertical(tuple(gravity_g))
        pipe.step(tuple(accel_phone[i]), tuple(gyro_phone[i]), float(t[i]), float(speed[i]))
        if i % 10 == 0:
            outputs.append([i] + pipe.outputs())
            mounts.append([i, pipe.mount.state] + [v for row in pipe.mount.rows() for v in row])

    # 1 Hz GPS along the driven path + barometer, through elevation fusion and the odometer
    heading = np.cumsum(yaw) / FS
    north = np.cumsum(speed * np.cos(heading)) / FS
    west = np.cumsum(speed * np.sin(heading)) / FS          # left turn -> heading increases -> drifts west
    fusion = lp.ElevationFusion()
    odo = lp.Odometer()
    fixes, nodes = [], []
    for k in range(0, n, int(FS)):
        lat = LAT0 + north[k] / 110540.0
        lon = LON0 - west[k] / (111320.0 * math.cos(math.radians(LAT0)))
        baro_rel = 0.12 * t[k]
        gps_alt = 200.0 + 0.12 * t[k] + float(rng.normal(0, 1.5))
        fusion.relative_baro_m = baro_rel
        fusion.ingest_gps(gps_alt, 4.0)
        elev = fusion.elevation()
        rough = pipe.take_segment_rough_rms()
        emitted = odo.feed(lat, lon, elev, float(speed[k]), 5.0, rough)
        fixes.append([float(t[k]), lat, lon, gps_alt, baro_rel, float(speed[k])])
        nodes.append(emitted)

    return {
        "about": "Generated by tools/make_live_fixture.py from core/live_pipeline.py -- do not edit.",
        "fs_hz": FS,
        "calibrate_at_index": calibrated_at,
        "gravity_g": gravity_g.tolist(),
        "true_veh_to_phone": R.tolist(),
        "t": t.tolist(),
        "speed": speed.tolist(),
        "accel": accel_phone.tolist(),
        "gyro": gyro_phone.tolist(),
        "outputs_every_10": outputs,
        "output_fields": ["index", "lon_acc", "lat_acc", "yaw_rate", "crest_acc", "hp_vert", "rough_mean_sq", "camber", "engagement"],
        "mount_every_10": mounts,
        "gps": fixes,
        "gps_fields": ["t", "lat", "lon", "gps_alt_m", "baro_rel_m", "speed_mps"],
        "gps_vertical_accuracy_m": 4.0,
        "gps_horizontal_accuracy_m": 5.0,
        "nodes_per_fix": nodes,
        "rough_rms_per_fix_note": "odometer is fed the IMU segment roughness RMS at the end of the run (constant)",
        "rough_rms_for_odometer": pipe.take_segment_rough_rms(),
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = json.dumps(build(), separators=(",", ":"))
    if args.check:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            print(f"{OUT} is stale: run python tools/make_live_fixture.py")
            return 1
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"Wrote {OUT} ({len(text) / 1e6:.2f} MB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
