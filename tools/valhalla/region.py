"""The own Quick-route server's region (backend/src/valhalla_region.ts) from the states' Geofabrik outlines.

Our Valhalla tiles (.github/workflows/valhalla-tiles.yml) are built from the Geofabrik extracts of these states, and an
extract holds what lies inside its .poly, so the same outlines say which requests our server can answer. A request with
any point outside them goes to the public server instead (backend/src/valhalla.ts).

    python -m tools.valhalla.region          # rewrite backend/src/valhalla_region.ts
    python -m tools.valhalla.region --check  # fail when it is out of date (tests/test_valhalla.py)
"""
import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
POLYS = ROOT / "tools" / "osm_ctx" / "polys"
OUT = ROOT / "backend" / "src" / "valhalla_region.ts"
STATES = ("ohio", "kentucky", "indiana")


def rings(path: pathlib.Path) -> list[list[tuple[float, float]]]:
    """A .poly file's outer rings as [(lon, lat)]. Holes (sections named !...) are not used by these states."""
    lines = [ln.strip() for ln in path.read_text().splitlines()]
    out, cur = [], None
    for ln in lines[1:]:
        if not ln:
            continue
        if ln == "END":
            if cur is not None:
                out.append(cur)
                cur = None
            continue
        if cur is None:
            if ln.startswith("!"):
                raise ValueError(f"{path.name}: holes are not supported")
            cur = []
            continue
        lon, lat = (float(v) for v in ln.split())
        cur.append((lon, lat))
    return out


def render() -> str:
    parts = []
    for s in STATES:
        for r in rings(POLYS / f"{s}.poly"):
            flat = ",".join(f"{lon:.4f},{lat:.4f}" for lon, lat in r)
            parts.append(f"  // {s}\n  [{flat}],")
    return (
        "// Generated by tools/valhalla/region.py from tools/osm_ctx/polys (the Geofabrik outlines our Valhalla tiles are built from).\n"
        "// Do not edit: run `python -m tools.valhalla.region`. Each ring is lon,lat pairs, flat.\n"
        f"export const REGION_STATES = {list(STATES)!r};\n".replace("'", '"')
        + "export const REGION_RINGS: number[][] = [\n" + "\n".join(parts) + "\n];\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python -m tools.valhalla.region", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
